#!/bin/bash
# ==============================================================================
# Script dừng toàn bộ hệ thống Intelligent Enterprise Email Automation
# Dừng: Frontend (3000), Backend (4000), n8n (5678) & PostgreSQL (5432)
# ==============================================================================

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
cd "$DIR"

echo "======================================================================"
echo "🛑 [1/3] Đang dừng Next.js Frontend (Cổng 3000)..."
echo "======================================================================"
fuser -k 3000/tcp 2>/dev/null || true
echo "✅ Frontend đã dừng."

echo ""
echo "======================================================================"
echo "🛑 [2/3] Đang dừng NestJS Backend (Cổng 4000)..."
echo "======================================================================"
fuser -k 4000/tcp 2>/dev/null || true
echo "✅ Backend đã dừng."

echo ""
echo "======================================================================"
echo "🛑 [3/3] Đang dừng Docker Containers (PostgreSQL & n8n)..."
echo "======================================================================"
docker compose down
echo "✅ Cơ sở dữ liệu và n8n đã dừng an toàn."

echo ""
echo "======================================================================"
echo "🎉 TOÀN BỘ HỆ THỐNG ĐÃ ĐƯỢC TẮT HOÀN TOÀN!"
echo "======================================================================"
